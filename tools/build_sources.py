"""Regenerate source_files.js, which embeds source files for the website's code explorer.

Run from the repo root after editing any of the files below:  python3 tools/build_sources.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = {
    "python": "source/agent_fx_demo.py",
    "web": "simulator.js",
    "notes": "source/ARCHITECTURE.md",
}

sources = {key: (ROOT / path).read_text(encoding="utf-8") for key, path in FILES.items()}
out = "// Generated by tools/build_sources.py. Do not edit by hand.\nwindow.SOURCE_FILES = " + json.dumps(sources, indent=1) + ";\n"
(ROOT / "source_files.js").write_text(out, encoding="utf-8")
print("Wrote source_files.js:", ", ".join(f"{k} ({len(v.splitlines())} lines)" for k, v in sources.items()))
